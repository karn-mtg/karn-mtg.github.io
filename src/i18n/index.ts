export function getLang(locale: string | undefined): Lang {
  if (locale === 'pt-br') return 'pt-br'
  if (locale === 'de') return 'de'
  if (locale === 'es') return 'es'
  return 'en'
}

export function contentPrefix(lang: Lang): string {
  return `${lang}/`
}

